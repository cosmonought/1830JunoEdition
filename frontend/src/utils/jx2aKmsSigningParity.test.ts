/* `elliptic` is @cosmjs/crypto's own secp256k1 dependency (no @types in this tree): only the calls used here are typed. */
interface EllipticSignature {
  readonly r: { toString(base: 16): string };
  readonly s: { toString(base: 16): string };
  toDER(): number[];
}
interface EllipticKey {
  sign(message: Buffer, options: { canonical?: boolean; pers?: Buffer }): EllipticSignature;
  getPublic(compact: boolean, encoding: "array"): number[];
}
interface EllipticCurve {
  keyFromPrivate(secret: Buffer): EllipticKey;
  genKeyPair(): EllipticKey;
}
// eslint-disable-next-line @typescript-eslint/no-var-requires
const { ec: EC } = require("elliptic") as { ec: new (curve: string) => EllipticCurve };
const secp = new EC("secp256k1");
const KEY_ARN = "arn:aws:kms:us-east-1:000000000000:key/00000000-0000-4000-8000-0000000000aa";

interface FakeKms extends KmsClient {
  readonly asked: Buffer[];
  readonly answered: { readonly der: Buffer; readonly highS: boolean }[];
  readonly spki: Buffer;
  readonly publicKeyObject: KeyObject;
}

/** A secp256k1 key made by OpenSSL, held only in memory; KMS's two calls over it. */
function disposableKms(): FakeKms {
  const { privateKey, publicKey } = generateKeyPairSync("ec", { namedCurve: "secp256k1" });
  const jwk = privateKey.export({ format: "jwk" }) as { d: string };
  const key = secp.keyFromPrivate(Buffer.from(jwk.d, "base64url"));
  const spki = publicKey.export({ type: "spki", format: "der" }) as Buffer;
  const asked: Buffer[] = [];
  const answered: { der: Buffer; highS: boolean }[] = [];
  let calls = 0;
  return {
    asked,
    answered,
    spki,
    publicKeyObject: createPublicKey({ key: spki, format: "der", type: "spki" }),
    async getPublicKey(keyRef) {
      expect(keyRef).toBe(KEY_ARN);
      return Uint8Array.from(spki);
    },
    async signDigest(keyRef, digest) {
      expect(keyRef).toBe(KEY_ARN);
      expect(digest.length).toBe(32);
      asked.push(Buffer.from(digest));
      calls += 1;
      const signature = key.sign(Buffer.from(digest), { canonical: false, pers: randomBytes(32) });
      let s = BigInt(`0x${signature.s.toString(16)}`);
      if (s <= HALF_N && calls % 2 === 0) s = SECP256K1_N - s; // the high-s twin: still a valid ECDSA signature
      const der = derOf(BigInt(`0x${signature.r.toString(16)}`), s);
      answered.push({ der, highS: s > HALF_N });
      return Uint8Array.from(der);
    },
  };
}

/** Minimal DER `ECDSA-Sig-Value` (what KMS answers). */
function derOf(r: bigint, s: bigint): Buffer {
  const int = (value: bigint) => {
    let body = bigIntTo32(value);
    while (body.length > 1 && body[0] === 0 && !(body[1] & 0x80)) body = body.subarray(1);
    if (body[0] & 0x80) body = Buffer.concat([Buffer.from([0]), body]);
    return Buffer.concat([Buffer.from([0x02, body.length]), body]);
  };
  const seq = Buffer.concat([int(r), int(s)]);
  return Buffer.concat([Buffer.from([0x30, seq.length]), seq]);
}

