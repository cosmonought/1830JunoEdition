// ==================================================================
//  JX-2A: THE RELAYER'S KMS SIGNING PIPELINE, END TO END, WITH A DISPOSABLE LOCAL KEY -- EVERY RELAYER ROUTE
// ==================================================================
//
// What the relayer does for every escrow transaction (`server/src/escrow/juno/relayer.ts` `advance`), step by step, with
// the PRODUCTION modules and only the KMS call replaced:
//
//   escrow intent (RELAYER_EXECUTE.<route>)  ->  decideGas (the policy's gas limit and fee)
//   ->  prepareExecuteTx (MsgExecuteContract, TxBody, AuthInfo, SignDoc, SHA-256 digest)
//   ->  openKmsDigestSigner.sign (the KMS port: DER ECDSA over the DIGEST -> strict DER parse -> r||s -> low-s ->
//       verify-before-use under the key GetPublicKey reported)
//   ->  assembleTx (TxRaw, tx hash)
//
// and then, as the chain does, INDEPENDENTLY: the TxRaw is decoded with cosmjs-types, every field is read back, the
// SignDoc is rebuilt by @cosmjs/proto-signing from the DECODED bytes, and the signature is verified by @cosmjs/crypto AND
// by Node's OpenSSL over the sign bytes. Three implementations agree with the server's hand encoder.
//
// THE FAKE KMS is independent of the server's secp256k1 code: the key is generated by Node's OpenSSL (its SPKI export is
// what GetPublicKey answers), and Sign is `elliptic` over the 32-byte digest with a RANDOM personalisation (so the
// signature is NOT deterministic, as real KMS ECDSA is not) and canonical:false (so high-s answers occur; every other
// low-s answer is also returned as its high-s twin, so the normalisation path is certainly exercised). Its answer is
// minimal DER, as KMS answers.
//
// Nothing here reads a network, AWS or a file key: the key exists only in this process and is discarded. Nothing is
// broadcast. The only thing allowed to differ between two signings of the same transaction is the signature (and so the
// TxRaw bytes and the tx hash); the sign bytes may not.

