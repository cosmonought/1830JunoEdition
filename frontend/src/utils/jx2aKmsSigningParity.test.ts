type Vector = (typeof vectors.payload_vectors)[number];
const settleVector = vectors.payload_vectors.find((v) => v.usage === "Settle" && v.payload.seat_count === 6) as Vector;
const checkpointVector = vectors.payload_vectors.find((v) => v.usage === "Checkpoint") as Vector;
/** Test-only secrets (a settlement key and the seats' consent keys) for representative, VALID inner signatures. */
const SETTLEMENT_SECRET = sha("jx2a/settlement");
const seatSecret = (seat: number) => sha(`jx2a/consent/${seat}`);
const CHAIN_GAME_ID = "18446744073709551615"; // u64::MAX: the JSON integer path at its edge

const POLICY: GasPolicy = { ...DEFAULT_GAS_POLICY, feeDenom: "ujunox" };
/** L6-12D's `perTransactionFeeCap` (server `aws/deploy/junoChain.ts`), restated with the same `ceilDiv`: that module pulls the
 *  server's configuration types, which this tree's es5 typecheck does not compile. The server-side JX-2A suite asserts the
 *  two are the same function of the policy. */
const perTransactionFeeCap = (gas: GasPolicy): bigint => {
  const derived = ceilDiv(gas.maxGas * gas.gasPriceNum, gas.gasPriceDen);
  return gas.maxFee < derived ? gas.maxFee : derived;
};

interface Route {
  readonly name: string;
  readonly msgJson: string;
  /** A representative node answer for the simulation (the floor, the middle, and the exact max_gas boundary). */
  readonly simulatedGas: string;
}

function routes(): Route[] {
  const settleSig = signDigest(SETTLEMENT_SECRET, Buffer.from(settleVector.settle_digest, "hex")).toString("hex");
  const checkpointSig = signDigest(SETTLEMENT_SECRET, Buffer.from(checkpointVector.settle_digest, "hex")).toString("hex");
  const consentDigest = consentDigestV1(settleVector.payload.domain, BigInt(settleVector.payload.seq), settleVector.settle_digest);
  expect(consentDigest).toBe(settleVector.consent_digest);
  const consentSig = signDigest(seatSecret(2), Buffer.from(consentDigest, "hex")).toString("hex");
  const annulDigest = annulDigestV1(checkpointVector.payload.domain, BigInt(checkpointVector.payload.seq));
  const annulConsents = Array.from({ length: checkpointVector.payload.seat_count }, (_, seat) => ({ seat_index: seat, signature: signDigest(seatSecret(seat), Buffer.from(annulDigest, "hex")).toString("hex") }));
  return [
    { name: "Start", msgJson: RELAYER_EXECUTE.start(CHAIN_GAME_ID, sha("jx2a/roster").toString("hex")), simulatedGas: "151234" },
    { name: "Checkpoint", msgJson: RELAYER_EXECUTE.checkpoint("42", checkpointVector.payload as never, checkpointSig), simulatedGas: "420017" },
    { name: "Consent", msgJson: RELAYER_EXECUTE.consent("42", 2, consentSig), simulatedGas: "200001" },
    // The exact max_gas boundary: ceil(1,153,846 x 13/10) = 1,500,000 = max_gas, so the fee is the per-transaction cap.
    { name: "Settle", msgJson: RELAYER_EXECUTE.settle("42", settleVector.payload as never, settleSig), simulatedGas: "1153846" },
    // Below the floor: the gas limit is min_gas (80,000).
    { name: "Finalize", msgJson: RELAYER_EXECUTE.finalize("42"), simulatedGas: "61000" },
    { name: "AnnulByConsent", msgJson: RELAYER_EXECUTE.annulByConsent("42", annulConsents), simulatedGas: "333333" },
  ];
}

